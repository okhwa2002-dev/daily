import { describe, expect, it } from 'vitest'
import { normalizeClientTimestamp } from './sync-time.ts'

/** 미래 시각 판정을 고정하기 위한 기준 시각 — 2026-08-10 12:00 KST */
const NOW = new Date('2026-08-10T03:00:00.000Z')
const norm = (s: string) => normalizeClientTimestamp(s, NOW)

describe('normalizeClientTimestamp', () => {
  it('UTC ISO를 KST 벽시계로 바꾼다', () => {
    expect(norm('2026-08-10T03:00:00.000Z')).toBe('2026-08-10 12:00:00.000')
  })

  it('KST 오프셋이 붙은 ISO를 그대로 해석한다', () => {
    // fromKstTimestamp에 그냥 넘기면 '+09:00+09:00'이 되어 Invalid Date가 나던 형태
    expect(norm('2026-08-10T12:00:00+09:00')).toBe('2026-08-10 12:00:00.000')
  })

  it('다른 타임존의 ISO도 KST로 옮긴다', () => {
    // 2026-08-09 23:00 EDT(-04:00) = 2026-08-10 03:00 UTC = 12:00 KST
    expect(norm('2026-08-09T23:00:00-04:00')).toBe('2026-08-10 12:00:00.000')
    // 콜론 없는 오프셋도 받는다
    expect(norm('2026-08-09T23:00:00-0400')).toBe('2026-08-10 12:00:00.000')
  })

  it('타임존 없는 문자열은 KST 벽시계로 본다', () => {
    expect(norm('2026-08-10 11:59:00.123')).toBe('2026-08-10 11:59:00.123')
    expect(norm('2026-08-10T11:59:00')).toBe('2026-08-10 11:59:00.000')
  })

  it('밀리초 자릿수를 3자리로 채운다', () => {
    expect(norm('2026-08-10 11:59:00.1')).toBe('2026-08-10 11:59:00.100')
    expect(norm('2026-08-10 11:59:00.12')).toBe('2026-08-10 11:59:00.120')
  })

  it('앞뒤 공백을 무시한다', () => {
    expect(norm('  2026-08-10T03:00:00.000Z  ')).toBe('2026-08-10 12:00:00.000')
  })

  // --- 여기서부터가 이 함수가 존재하는 이유다 ---

  it.each([
    ['빈 문자열', ''],
    ['공백뿐', '   '],
    ['쓰레기 값', 'not-a-date'],
    ['날짜만', '2026-08-10'],
    ['시각만', '12:00:00'],
    ['존재하지 않는 날짜', '2026-02-30 00:00:00'],
    ['존재하지 않는 날짜 (ISO)', '2026-02-30T00:00:00Z'],
    ['4월 31일', '2026-04-31T00:00:00Z'],
    ['범위를 넘는 시각', '2026-08-10 25:00:00'],
  ])('해석할 수 없는 값은 던진다 — %s', (_label, value) => {
    expect(() => norm(value)).toThrow()
  })

  it('Invalid Date를 조용히 반환하지 않는다', () => {
    // 이 함수의 유일한 실패 모드는 "던지는 것"이어야 한다.
    // NaN이 새어나가면 LWW 비교가 전부 false가 되어 수정이 조용히 사라진다.
    let result: string | undefined
    try { result = norm('garbage') } catch { /* 기대한 경로 */ }
    expect(result).toBeUndefined()
  })

  it('서버 시각보다 5분 넘게 앞선 값은 거부한다', () => {
    // NOW + 6분
    expect(() => norm('2026-08-10T03:06:00.000Z')).toThrow(/앞섭/)
  })

  it('5분 이내로 앞선 값은 받는다 — 정상적인 시계 오차', () => {
    expect(norm('2026-08-10T03:04:00.000Z')).toBe('2026-08-10 12:04:00.000')
  })

  it('과거 값은 얼마나 오래됐든 받는다', () => {
    // 오래된 값은 LWW에서 지기만 할 뿐 위험하지 않다.
    expect(norm('2020-01-01T00:00:00.000Z')).toBe('2020-01-01 09:00:00.000')
  })

  it('정규화 결과는 DB 저장 형식과 정확히 일치한다', () => {
    expect(norm('2026-08-10T03:00:00.000Z')).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}$/)
  })
})
